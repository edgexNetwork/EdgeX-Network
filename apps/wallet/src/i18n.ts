import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { readGlobalData, writeGlobalData } from "./core/globalData";








export type Lang = "zh" | "en" | "ru" | "ja";


export const LANG_ORDER: readonly Lang[] = ["zh", "en", "ru", "ja"];


export const LANG_BUTTON_LABEL: Record<Lang, string> = {
  zh: "[中文]",
  en: "[EN]",
  ru: "[РУС]",
  ja: "[日本語]",
};


export const UI_STATE_FILE_NAME = "ui-state.json";


export function nextLang(current: Lang): Lang {
  const idx = LANG_ORDER.indexOf(current);
  return LANG_ORDER[(idx + 1) % LANG_ORDER.length];
}


export function detectLang(env: NodeJS.ProcessEnv = process.env): Lang {
  const raw =
    [env.LANGUAGE, env.LC_ALL, env.LC_MESSAGES, env.LANG].find((v) => v !== undefined && v !== "") ?? "";
  const code = raw.toLowerCase();
  if (code.startsWith("zh")) return "zh";
  if (code.startsWith("ru")) return "ru";
  if (code.startsWith("ja")) return "ja";
  if (code.startsWith("en")) return "en";
  try {
    const loc = new Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase();
    if (loc.startsWith("zh")) return "zh";
    if (loc.startsWith("ru")) return "ru";
    if (loc.startsWith("ja")) return "ja";
    if (loc.startsWith("en")) return "en";
  } catch {

  }
  return "zh";
}


export function loadLang(datadir: string): Lang | null {
  try {
    const stored = readGlobalData("ui.lang");
    if (stored === "zh" || stored === "en" || stored === "ru" || stored === "ja") return stored;
    const legacyPath = path.join(datadir, UI_STATE_FILE_NAME);
    if (!existsSync(legacyPath)) return null;
    const raw = JSON.parse(readFileSync(legacyPath, "utf8")) as {
      lang?: unknown;
    };
    if (raw?.lang !== "zh" && raw?.lang !== "en" && raw?.lang !== "ru" && raw?.lang !== "ja") return null;
    writeGlobalData("ui.lang", raw.lang);
    return raw.lang;
  } catch {
    return null;
  }
}


export function saveLang(datadir: string, lang: Lang): void {
  try {
    void datadir;
    writeGlobalData("ui.lang", lang);
  } catch {

  }
}


export function applyStoredLang(datadir: string): Lang {
  const lang = loadLang(datadir) ?? detectLang();
  setLang(lang);
  return lang;
}


export function localeOf(lang: Lang): string {
  switch (lang) {
    case "zh":
      return "zh-CN";
    case "ru":
      return "ru-RU";
    case "ja":
      return "ja-JP";
    default:
      return "en-US";
  }
}


export function currentLocale(): string {
  return localeOf(getLang());
}

