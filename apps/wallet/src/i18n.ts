const DICTS: Record<Lang, Dict> = { zh: ZH, en: EN, ru: RU, ja: JA };


let currentLang: Lang = "zh";

export function getLang(): Lang {
  return currentLang;
}


export function setLang(lang: Lang): void {
  currentLang = lang;
}


export function t(key: string, vars?: Record<string, string | number>): string {
  const text = DICTS[currentLang][key] ?? ZH[key] ?? key;
  if (vars === undefined) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}


export function assertCompleteDictionaries(): void {
  const base = Object.keys(ZH).sort();
  for (const lang of LANG_ORDER) {
    const keys = Object.keys(DICTS[lang]).sort();
    if (JSON.stringify(keys) !== JSON.stringify(base)) {
      throw new Error(`i18n dictionary mismatch for ${lang}`);
    }
  }
}
